/* Aplica un idioma: recorre [data-i18n] (contenido de texto) y
   [data-i18n-attr="atributo:clave"] (atributos como alt), actualiza
   <html lang="...">, y guarda la elección en localStorage. */
function applyLanguage(lang) {
  var dict = I18N[lang] || I18N.es;

  document.querySelectorAll('[data-i18n]').forEach(function (el) {
    var key = el.getAttribute('data-i18n');
    if (Object.prototype.hasOwnProperty.call(dict, key)) {
      el.innerHTML = dict[key];
    }
  });

  document.querySelectorAll('[data-i18n-attr]').forEach(function (el) {
    el.getAttribute('data-i18n-attr').split(',').forEach(function (pair) {
      var parts = pair.split(':');
      var attr = parts[0];
      var key = parts[1];
      if (attr && key && Object.prototype.hasOwnProperty.call(dict, key)) {
        el.setAttribute(attr, dict[key]);
      }
    });
  });

  document.documentElement.setAttribute('lang', lang === 'pt-BR' ? 'pt-BR' : lang);

  document.querySelectorAll('#langSelect').forEach(function (sel) {
    sel.value = lang;
  });

  try { localStorage.setItem('caffe-moretti-lang', lang); } catch (e) {}
}

(function () {
  var LANG_KEY = 'caffe-moretti-lang';
  var stored = null;
  try { stored = localStorage.getItem(LANG_KEY); } catch (e) {}
  var initial = (stored && I18N[stored]) ? stored : 'es';

  document.addEventListener('DOMContentLoaded', function () {
    applyLanguage(initial);
    document.querySelectorAll('#langSelect').forEach(function (sel) {
      sel.addEventListener('change', function () {
        applyLanguage(sel.value);
      });
    });
  });
})();
